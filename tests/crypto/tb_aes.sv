                if (count > 100)
                    $fatal(1, "Request stalled");
            end
            @(negedge clk);
            req_valid = 0;
            count = 0;
            while (!rsp_valid)
            begin
                @(negedge clk);
                count = count + 1;
                if (count > 100)
                    $fatal(1, "Response stalled");
            end
            held = rsp_rdata;
            held_error = rsp_error;
            repeat (3)
            begin
                @(negedge clk);
                if (!rsp_valid || rsp_rdata !== held || rsp_error !== held_error)
                    $fatal(1, "Held response changed");
            end
            if (held_error !== error)
                $fatal(1, "Error mismatch offset%0d wr%0d got%0b expected%0b data%08h", off, wr,
                       held_error, error, held);
            if (error && held !== 0)
                $fatal(1, "Error response exposed data");
            got = held;
            checks = checks + 1;
            rsp_ready = 1;
            @(negedge clk);
            rsp_ready = 0;
        end
    endtask
    task wr
        (input [7 : 0] off,
         input [31 : 0] data);
        reg [31 : 0] ignored;
        begin
            access(1, off, data, 15, 0, ignored);
        end
    endtask
    task rd
        (input [7 : 0] off,
         input [31 : 0] expected);
        reg [31 : 0] got;
        begin
            access(0, off, 0, 15, 0, got);
            if (got !== expected)
                $fatal(1, "Read mismatch offset%0d got%08h expected%08h", off, got, expected);
        end
    endtask
    task wipe;
        reg [31 : 0] status;
        integer count;
        begin
            wr(16, 2);
            count = 0;
            access(0, 12, 0, 15, 0, status);
            while (status[0])
            begin
                repeat (20) @(negedge clk)
                    ;
                access(0, 12, 0, 15, 0, status);
                count = count + 1;
                if (count > 1000)
                    $fatal(1, "Wipe timeout");
            end
            if (status !== 0)
                $fatal(1, "Wipe status not zero");
            for (j = 0; j < 1024; j = j + 1)
                if (dut.packet[j] !== 0)
                    $fatal(1, "Packet RAM not wiped at%0d", j);
            if (dut.nonce_registers !== 0 || dut.aad_registers !== 0 || dut.tag_registers !== 0)
                $fatal(1, "Parameter secret survives clear");
            for (j = 0; j < 64; j = j + 1)
                if (dut.engine.cipher.round_keys[j] !== 0)
                    $fatal(1, "Key RAM survives clear");
        end
    endtask
    task completion
        (input good);
        reg [31 : 0] status;
        integer count;
        begin
            count = 0;
            access(0, 12, 0, 15, 0, status);
            while (!status[1])
            begin
                repeat (20) @(negedge clk)
                    ;
                access(0, 12, 0, 15, 0, status);
                count = count + 1;
                if (count > 10000)
                    $fatal(1, "Packet timeout phase%0d", dut.engine.phase);
            end
            if (status !== (good ? 32'd6 : 32'd10))
                $fatal(1, "Completion status wrong %08h", status);
            if (!good)
                for (j = 0; j < 1024; j = j + 1)
                    if (dut.packet[j] !== 0)
                        $fatal(1, "Unauthenticated plaintext retained");
            cases = cases + 1;
        end
    endtask
